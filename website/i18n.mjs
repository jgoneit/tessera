const supported = language => Object.hasOwn(messages, language);

export function resolveLanguage({ requested, saved, preferred = [] } = {}) {
  if (supported(requested)) return requested;
  if (supported(saved)) return saved;
  for (const language of preferred) {
    const base = String(language).toLowerCase().split('-')[0];
    if (supported(base)) return base;
  }
  return 'en';
}

export function t(language, key, values = {}) {
  const template = messages[supported(language) ? language : 'en'][key];
  if (template === undefined) throw new Error(`Unknown translation: ${key}`);
  return template.replace(/\{(\w+)\}/g, (_, name) => {
    if (!Object.hasOwn(values, name)) throw new Error(`Missing translation value: ${name}`);
    return String(values[name]);
  });
}

export function translateDocument(document, language) {
  document.documentElement.lang = language;
  document.title = t(language, 'meta.title');
  for (const [selector, key] of [
    ['meta[name="description"]', 'meta.description'],
    ['meta[property="og:title"]', 'meta.title'],
    ['meta[property="og:description"]', 'meta.socialDescription']
  ]) document.querySelector(selector).setAttribute('content', t(language, key));
  for (const element of document.querySelectorAll('[data-i18n]')) {
    element.textContent = t(language, element.dataset.i18n);
  }
  for (const attribute of ['aria-label', 'title']) {
    const binding = `data-i18n-${attribute}`;
    for (const element of document.querySelectorAll(`[${binding}]`)) {
      element.setAttribute(attribute, t(language, element.getAttribute(binding)));
    }
  }
}
